#!/usr/bin/env node
// agent-stack installer — local web UI on http://127.0.0.1:7070
// Pure Node built-ins (http, fs, child_process, path, url, crypto). No npm deps.

import http from 'node:http';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import crypto from 'node:crypto';

const HOST = '127.0.0.1';
const PORT = 7070;
const DEMO = process.env.INSTALLER_DEMO === '1';
const STACK_DIR = process.env.STACK_DIR || '/opt/agent-stack';
const HERE = path.dirname(url.fileURLToPath(import.meta.url));

// --- helpers ----------------------------------------------------------------

function sendJSON(res, code, obj) {
  const body = JSON.stringify(obj);
  res.writeHead(code, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
    'Cache-Control': 'no-store',
  });
  res.end(body);
}

function sendText(res, code, text, type = 'text/plain; charset=utf-8') {
  res.writeHead(code, { 'Content-Type': type, 'Cache-Control': 'no-store' });
  res.end(text);
}

function readBody(req, limitBytes = 1024 * 256) {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks = [];
    req.on('data', (c) => {
      size += c.length;
      if (size > limitBytes) {
        reject(new Error('body too large'));
        req.destroy();
        return;
      }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

// Run a command (no shell — array argv), capture stdout. Resolves even on non-zero.
function probe(cmd, args, timeoutMs = 4000) {
  return new Promise((resolve) => {
    let done = false;
    let out = '';
    let err = '';
    let child;
    try {
      child = spawn(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (e) {
      resolve({ ok: false, version: '', error: String(e.message || e) });
      return;
    }
    const timer = setTimeout(() => {
      if (done) return;
      done = true;
      try { child.kill('SIGKILL'); } catch {}
      resolve({ ok: false, version: '', error: 'timeout' });
    }, timeoutMs);
    child.stdout.on('data', (c) => (out += c.toString()));
    child.stderr.on('data', (c) => (err += c.toString()));
    child.on('error', (e) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve({ ok: false, version: '', error: String(e.message || e) });
    });
    child.on('close', (code) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      const version = (out || err).trim().split('\n')[0] || '';
      resolve({ ok: code === 0, version, error: code === 0 ? '' : (err.trim() || `exit ${code}`) });
    });
  });
}

// --- /api/detect ------------------------------------------------------------

async function handleDetect(res) {
  const [nodeR, claudeR, codexR, geminiR, caddyR] = await Promise.all([
    probe('node', ['--version']),
    probe('/usr/bin/claude', ['--version']).then((r) => r.ok ? r : probe('claude', ['--version'])),
    probe('codex', ['--version']),
    probe('gemini', ['--version']),
    probe('caddy', ['version']),
  ]);
  const stackOk = fs.existsSync(STACK_DIR);
  sendJSON(res, 200, {
    node: nodeR,
    claude: claudeR,
    codex: codexR,
    gemini: geminiR,
    caddy: caddyR,
    stack: { ok: stackOk, version: stackOk ? STACK_DIR : '' },
    demo: DEMO,
  });
}

// --- /api/env ---------------------------------------------------------------

function safeStr(v, fallback = '') {
  if (v === undefined || v === null) return fallback;
  const s = String(v);
  // strip CR/LF to avoid sneaking new KEY=val lines
  return s.replace(/[\r\n]+/g, ' ').trim();
}

function pickEnum(v, allowed, fallback) {
  const s = safeStr(v);
  return allowed.includes(s) ? s : fallback;
}

function rand(n = 48) {
  return crypto.randomBytes(n).toString('base64url').slice(0, n);
}

function buildProxyEnv(cfg) {
  const backend = pickEnum(cfg.LLM_BACKEND, ['cli', 'api'], 'cli');
  const cliProvider = pickEnum(cfg.CLI_PROVIDER, ['claude', 'codex', 'gemini'], 'claude');
  const proxyKey = safeStr(cfg.PROXY_API_KEY) || rand(48);
  const jwtSecret = safeStr(cfg.JWT_SECRET) || rand(48);
  const lines = [
    '# generated by agent-stack installer',
    'HOST=127.0.0.1',
    'PORT=3001',
    `LLM_BACKEND=${backend}`,
    `CLI_PROVIDER=${cliProvider}`,
    `CLI_MODEL=${safeStr(cfg.CLI_MODEL)}`,
    'CLI_TIMEOUT_MS=120000',
    `KIMI_BASE_URL=${safeStr(cfg.KIMI_BASE_URL)}`,
    `KIMI_API_KEY=${safeStr(cfg.KIMI_API_KEY)}`,
    `KIMI_MODEL=${safeStr(cfg.KIMI_MODEL)}`,
    `PROXY_API_KEY=${proxyKey}`,
    `JWT_SECRET=${jwtSecret}`,
    `PUBLIC_BASE=${safeStr(cfg.PUBLIC_BASE)}`,
    '',
  ];
  return { content: lines.join('\n'), proxyKey, jwtSecret };
}

function buildUiEnv(cfg) {
  const lines = [
    '# generated by agent-stack installer',
    `AUTH_USER=${safeStr(cfg.AUTH_USER) || 'admin'}`,
    `AUTH_PASSWORD=${safeStr(cfg.AUTH_PASSWORD)}`,
    'KIMI_PROXY_URL=http://127.0.0.1:3001',
    '',
  ];
  return lines.join('\n');
}

async function handleEnv(req, res) {
  let body;
  try {
    body = JSON.parse(await readBody(req));
  } catch (e) {
    sendJSON(res, 400, { ok: false, error: 'bad json: ' + e.message });
    return;
  }
  const proxyDir = path.join(STACK_DIR, 'kimi-mcp-proxy');
  const uiDir = path.join(STACK_DIR, 'ai-chat-ui');
  const written = [];
  const proxyEnvPath = path.join(proxyDir, '.env');
  const uiEnvPath = path.join(uiDir, '.env.local');
  const { content: proxyContent, proxyKey } = buildProxyEnv(body);
  const uiContent = buildUiEnv(body);
  try {
    if (fs.existsSync(proxyDir)) {
      fs.writeFileSync(proxyEnvPath, proxyContent, { mode: 0o600 });
      written.push(proxyEnvPath);
    }
    if (fs.existsSync(uiDir)) {
      fs.writeFileSync(uiEnvPath, uiContent, { mode: 0o600 });
      written.push(uiEnvPath);
    }
  } catch (e) {
    sendJSON(res, 500, { ok: false, error: 'write failed: ' + e.message, written });
    return;
  }
  sendJSON(res, 200, { ok: true, written, proxyApiKey: proxyKey });
}

