function sseInit(res) {
  res.writeHead(200, {
    'Content-Type': 'text/event-stream; charset=utf-8',
    'Cache-Control': 'no-cache, no-transform',
    'Connection': 'keep-alive',
    'X-Accel-Buffering': 'no',
  });
}

function sseSend(res, event, data) {
  const lines = String(data).split('\n');
  if (event) res.write(`event: ${event}\n`);
  for (const ln of lines) res.write(`data: ${ln}\n`);
  res.write('\n');
}

function runSeq(res, jobs, onDone) {
  let idx = 0;
  const step = () => {
    if (idx >= jobs.length) { onDone(0); return; }
    const [cmd, args] = jobs[idx++];
    sseSend(res, null, `$ ${cmd} ${args.join(' ')}`);
    let child;
    try {
      child = spawn(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (e) {
      sseSend(res, null, 'ERROR: ' + e.message);
      onDone(1);
      return;
    }
    child.stdout.on('data', (c) => sseSend(res, null, c.toString().replace(/\n$/, '')));
    child.stderr.on('data', (c) => sseSend(res, null, c.toString().replace(/\n$/, '')));
    child.on('close', (code) => {
      if (code !== 0) {
        sseSend(res, null, `[exit ${code}]`);
        onDone(code || 1);
        return;
      }
      step();
    });
    child.on('error', (e) => { sseSend(res, null, 'spawn error: ' + e.message); onDone(1); });
  };
  step();
}

function runDemo(res, step, onDone) {
  const jobs = STEPS[step].real;
  let i = 0;
  const tick = () => {
    if (i >= jobs.length) { sseSend(res, null, 'DEMO: завершено успешно'); onDone(0); return; }
    const [cmd, args] = jobs[i++];
    sseSend(res, null, `[demo] would run: ${cmd} ${args.join(' ')}`);
    setTimeout(tick, 350);
  };
  sseSend(res, null, `[demo] шаг: ${STEPS[step].label}`);
  tick();
}

async function handleRun(req, res) {
  const parsed = url.parse(req.url, true);
  const step = String(parsed.query.step || '');
  if (!Object.prototype.hasOwnProperty.call(STEPS, step)) {
    sendJSON(res, 400, { ok: false, error: 'unknown step', allowed: Object.keys(STEPS) });
    return;
  }
  sseInit(res);
  sseSend(res, 'start', JSON.stringify({ step, demo: DEMO }));
  const onDone = (code) => {
    sseSend(res, 'done', JSON.stringify({ code }));
    res.end();
  };
  if (DEMO) runDemo(res, step, onDone);
  else runSeq(res, STEPS[step].real, onDone);
}

// --- /api/cli-login ---------------------------------------------------------

async function handleCliLogin(req, res) {
  let body = {};
  try { body = JSON.parse(await readBody(req)); } catch {}
  const provider = pickEnum(body.provider, ['claude', 'codex', 'gemini'], 'claude');
  if (DEMO) {
    sendJSON(res, 200, {
      ok: true,
      demo: true,
      message: `[demo] запустите вручную: ${provider} login (в интерактивном терминале)`,
      hint: 'CLI требует TTY — авторизуйтесь в обычной SSH-сессии, затем продолжайте мастер.',
    });
    return;
  }
  // Real CLI login needs a TTY — we can't drive it from a web request.
  // Return instructions instead of pretending to launch it.
  const cmd = provider === 'claude' ? '/usr/bin/claude login'
    : provider === 'codex' ? 'codex login'
    : 'gemini auth';
  sendJSON(res, 200, {
    ok: true,
    requiresTty: true,
    message: `Авторизация CLI требует терминал. Выполните в SSH-сессии: ${cmd}`,
    command: cmd,
  });
}

// --- static index.html ------------------------------------------------------

function handleIndex(res) {
  const p = path.join(HERE, 'index.html');
  try {
    const html = fs.readFileSync(p);
    res.writeHead(200, {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'no-store',
      'Content-Length': html.length,
    });
    res.end(html);
  } catch (e) {
    sendText(res, 500, 'index.html missing: ' + e.message);
  }
}

// --- router -----------------------------------------------------------------

const server = http.createServer(async (req, res) => {
  // hard guard: only local
  const ra = req.socket.remoteAddress || '';
  if (!(ra === '127.0.0.1' || ra === '::1' || ra === '::ffff:127.0.0.1')) {
    sendText(res, 403, 'forbidden: localhost only');
    return;
  }
  const u = url.parse(req.url || '/', true);
  const pathname = u.pathname || '/';
  try {
    if (req.method === 'GET' && pathname === '/') return handleIndex(res);
    if (req.method === 'GET' && pathname === '/api/detect') return handleDetect(res);
    if (req.method === 'POST' && pathname === '/api/env') return handleEnv(req, res);
    if (req.method === 'GET' && pathname === '/api/run') return handleRun(req, res);
    if (req.method === 'POST' && pathname === '/api/cli-login') return handleCliLogin(req, res);
    if (req.method === 'GET' && pathname === '/api/health') return sendJSON(res, 200, { ok: true, demo: DEMO });
    sendText(res, 404, 'not found');
  } catch (e) {
    sendJSON(res, 500, { ok: false, error: String(e.message || e) });
  }
});

server.listen(PORT, HOST, () => {
  process.stdout.write(
    `agent-stack installer on http://${HOST}:${PORT}  ` +
    `(demo=${DEMO ? 'on' : 'off'}, stack=${STACK_DIR})\n`
  );
});
